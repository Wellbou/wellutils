_t_param_EN() {
    case "$1" in
        usb_speed_unknown)  printf 'Unknown (%s Mbps)' "$2" ;;
        launcher_error_lang) printf 'unknown language "%s". Use RU or EN.' "$2" ;;
        *) return 1 ;;
    esac
}

_t_param_RU() {
    case "$1" in
        usb_speed_unknown)  printf 'Неизвестно (%s Мбит/с)' "$2" ;;
        launcher_error_lang) printf 'неизвестный язык "%s". Используйте RU или EN.' "$2" ;;
        *) return 1 ;;
    esac
}

# Plural forms: t_plural <n> <base> -- keys ${base}_one / ${base}_few / ${base}_many
t_plural() {
    local n="$1" base="$2" form
    if [[ "$WELLUTILS_LANG" == "RU" ]]; then
        local d10=$(( n % 10 )) d100=$(( n % 100 ))
        if (( d10 == 1 && d100 != 11 )); then form="one"
        elif (( d10 >= 2 && d10 <= 4 && ( d100 < 12 || d100 > 14 ) )); then form="few"
        else form="many"; fi
    else
        if (( n == 1 )); then form="one"; else form="many"; fi
    fi
    t "${base}_${form}"
}

t() {
    local _key="$1" _val=""
    if [[ "$WELLUTILS_LANG" == "RU" ]]; then
        if [[ -v "_T_RU[$_key]" ]]; then _val="${_T_RU[$_key]}"; fi
    else
        if [[ -v "_T_EN[$_key]" ]]; then _val="${_T_EN[$_key]}"; fi
    fi
    if [[ -z "$_val" ]]; then
        if [[ -v "_T_EN[$_key]" ]]; then _val="${_T_EN[$_key]}"; fi
    fi
    if [[ -z "$_val" ]]; then
        case "$WELLUTILS_LANG" in
            RU) _t_param_RU "$@" && return ;;
            *)  _t_param_EN "$@" && return ;;
        esac
        printf '%s' "$_key"
    else
        printf '%s' "$_val"
    fi
}
